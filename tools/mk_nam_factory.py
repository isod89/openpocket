# OpenPocket — writes engine/px_nam_factory.h: the factory NAM models (A2-Lite weights, names, level trims).
#   mk_nam_factory.py LIST.txt DIR [DI.wav]
# LIST.txt: one model a line, "id|NAME|source capture"; DIR/id.nam: the trained A2-Lite (tools/train_a2.py).
# Level trim: every model at the same loudness (ITU BS.1770, K-weighted) on the DI clip played at the captures' level,
# so that switching models keeps the volume (tools/nam_level.py does the same for the web editor's user models).
import json, os, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import nam_a2, nam_level

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def cfloat(v):
    """a C float literal that round-trips the float32 (0 -> 0.0f, 1e-05 -> 1e-05f)"""
    s = "%.9g" % float(v)
    if not any(c in s for c in ".en"):
        s += ".0"
    return s + "f"


def main():
    lst, d = sys.argv[1], sys.argv[2]
    di = sys.argv[3] if len(sys.argv) > 3 else None
    rows = [l.rstrip("\n").split("|") for l in open(lst) if l.strip()]
    names, lv, ws, srcs = [], [], [], []
    for mid, name, src in rows:
        j = json.load(open(os.path.join(d, mid + ".nam")))
        m, c = nam_a2.pick(j, "lite")
        if c != 3:
            raise SystemExit("%s: not A2-Lite" % mid)
        w = np.asarray(m["weights"], dtype=np.float32)
        ws.append(w)
        names.append(name[:11])
        srcs.append("%s (val ESR %s)" % (src, (m.get("metadata") or {}).get("val_esr", "?")))
        lv.append(nam_level.trim_db(nam_a2.unpack(w.astype(np.float64), 3), di))
        print("%-10s level trim %+.2f dB" % (name, lv[-1]))
    if len(ws) != 12:
        raise SystemExit("want 12 models, got %d" % len(ws))
    out = ["/* SPDX-License-Identifier: GPL-3.0-only",
           " * OpenPocket — the factory NAM models (generated by tools/mk_nam_factory.py: do not edit).",
           " * A2-Lite networks trained by tools/train_a2.py on real DI guitar (Alec-Wright/Automated-GuitarAmpModelling,",
           " * GPL v3) through NAM community captures (pelennor2170/NAM_models, GPL v3), at 44.1 kHz:"]
    for n, s in zip(names, srcs):
        out.append(" *   %-10s %s" % (n, s))
    out += [" */", "#pragma once",
            "/* PXN_KEEP: the factory models built in, one bit each (bit i: PXN_FNAME[i]), all by default. A model left out keeps its",
            " * place and its name's slot: the engine plays a kept one for it (engine/px_dsp.c pxn_fact), so presets and the MODEL",
            " * knob stay where they were (test build 28: the Bluetooth audio image keeps 4, firmware/build.sh) */",
            "#ifndef PXN_KEEP",
            "#define PXN_KEEP 0xFFFu",
            "#endif",
            "#define PXN_KB(i) ((PXN_KEEP >> (i)) & 1u)",
            "#define PXN_NROWS (PXN_KB(0) + PXN_KB(1) + PXN_KB(2) + PXN_KB(3) + PXN_KB(4) + PXN_KB(5) + PXN_KB(6) + PXN_KB(7) + \\",
            "                   PXN_KB(8) + PXN_KB(9) + PXN_KB(10) + PXN_KB(11))",
            "static const char *const PXN_FNAME[PX_NAM_NFACT] = {%s};" % ", ".join('"%s"' % n for n in names),
            "static const float PXN_FLVL[PX_NAM_NFACT] = {%s};" % ", ".join("%.2ff" % v for v in lv),
            "static const float PXN_FW[PXN_NROWS][PXN_NW] = {"]
    for k, w in enumerate(ws):
        vals = [cfloat(v) for v in w]
        lines = [", ".join(vals[i:i + 10]) for i in range(0, len(vals), 10)]
        out += ["#if PXN_KB(%d)" % k, "  {" + ",\n   ".join(lines) + "},", "#endif"]
    out.append("};")
    open(os.path.join(ROOT, "engine", "px_nam_factory.h"), "w").write("\n".join(out) + "\n")
    print("engine/px_nam_factory.h: %d models" % len(ws))


if __name__ == "__main__":
    main()
