/* What the controller and host libraries reference but this image never runs: Bluetooth classic (BR/EDR, LMP, eSCO, TWS,
 * its profiles), the GATT client, controller-side test modes, Wi-Fi coexistence and low-power negotiation. The configuration
 * (ble_cfg.c: LE only, one slave link, a GATT server) keeps the libraries from calling them; each is an empty function that
 * returns 0 and counts the call in ble_stub_calls, keeping its name in ble_stub_last, so a call that should not happen shows
 * in the link line.
 * Generated from the link errors of the "ble" target (list the names with: grep BLE_STUB firmware/ble/ble_stubs.c). */
#include <stdint.h>
#include "ble_status.h"

uint32_t ble_stub_calls;
const char *ble_stub_last, *ble_stub_seen[12];                  /* the different ones called, in order: the trace line */
/* some of these run in the radio's interrupt, inside the 150 us before an answer goes out: only the two stores there */
#define BLE_STUB(name) int name(void) { ble_stub_calls++; ble_stub_last = #name; return 0; }
#define BLE_STUB_SLOT(name) int name(void) { ble_stub_calls++; ble_stub_last = #name; ble_cnt_slot++; return 0; }
static void ble_stub_collect(void)                              /* from the main loop */
{
    const char *name = ble_stub_last;
    uint32_t i;
    for (i = 0; i < 12u; i++) {
        if (ble_stub_seen[i] == name) return;
        if (!ble_stub_seen[i]) { ble_stub_seen[i] = name; return; }
    }
}
